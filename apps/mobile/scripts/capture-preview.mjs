import { chromium, devices, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const output = new URL('../../../design/previews/', import.meta.url);
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const errors = [];
try {
  const context = await browser.newContext({ ...devices['iPhone 13'] });
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:8081');
  await expect(page.getByRole('button', { name: 'Demo' })).toBeVisible();
  await page.screenshot({ path: fileURLToPath(new URL('signin-iphone.png', output)) });
  await page.getByRole('button', { name: 'Demo' }).click();
  await expect(page.getByTestId('home-balance')).toBeVisible();
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.getByRole('button', { name: 'Demo' }).click();
  await expect(page.getByTestId('home-balance')).toHaveText('$1,240.50');
  await page.screenshot({ path: fileURLToPath(new URL('home-iphone.png', output)) });
  await page.getByRole('button', { name: 'Send to Mamá', exact: true }).click();
  await page.getByLabel('Amount in USDC', { exact: true }).fill('50');
  await page.getByLabel('Amount in USDC', { exact: true }).blur();
  await page.screenshot({ path: fileURLToPath(new URL('send-iphone.png', output)) });
  await page.getByTestId('review-transfer').click();
  await expect(page.getByTestId('confirm-transfer')).toBeVisible();
  await page.screenshot({ path: fileURLToPath(new URL('review-iphone.png', output)) });
  await page.goto('http://127.0.0.1:8081/family');
  await expect(page.getByText('Good things, together')).toBeVisible();
  await page.screenshot({ path: fileURLToPath(new URL('family-iphone.png', output)) });
  await page.setViewportSize({ width: 320, height: 740 });
  await page.goto('http://127.0.0.1:8081');
  await expect(page.getByTestId('home-balance')).toBeVisible();
  await page.screenshot({ path: fileURLToPath(new URL('home-small-phone.png', output)) });
  await page.setViewportSize({ width: 320, height: 568 });
  await page.goto('http://127.0.0.1:8081/sign-in');
  await expect(page.getByRole('button', { name: 'Demo' })).toBeVisible();
  await page.screenshot({ path: fileURLToPath(new URL('signin-small-phone.png', output)), fullPage: true });
  const desktop = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  desktop.on('pageerror', error => errors.push(error.message));
  await desktop.goto('http://127.0.0.1:8081');
  await desktop.getByRole('button', { name: 'Demo' }).click();
  await expect(desktop.getByTestId('home-balance')).toBeVisible();
  await desktop.screenshot({ path: fileURLToPath(new URL('home-web.png', output)) });
  if (errors.length) throw new Error(`Browser errors: ${errors.join('; ')}`);
  console.log('Captured phone, review, family, small-phone, and desktop previews; no browser page errors.');
} finally { await browser.close(); }
