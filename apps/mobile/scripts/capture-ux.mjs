import { chromium, devices, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const baseURL = process.env.NEST_PREVIEW_URL || 'http://127.0.0.1:8088';
const output = fileURLToPath(new URL('../../../design/previews/', import.meta.url));
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome' });
try {
  const page = await browser.newPage({ ...devices['iPhone 13'], viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  async function capture(name, anchor) {
    if (anchor) await anchor.scrollIntoViewIfNeeded();
    await page.evaluate(async () => { await document.fonts.ready; await Promise.all([...document.images].map(img => img.decode().catch(() => undefined))); });
    await page.screenshot({ path: `${output}nest-${name}.png`, animations: 'disabled' });
  }
  await page.goto(baseURL);
  await page.getByRole('button', { name: 'Demo', exact: true }).click();
  await page.getByTestId('home-balance').waitFor();
  await page.goto(`${baseURL}/money?mode=add`);
  await page.getByLabel('Amount in USDC', { exact: true }).fill('100');
  await page.getByRole('button', { name: 'Review details', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm demo top-up', exact: true }).click();
  await page.getByRole('button', { name: 'Back to home', exact: true }).click();
  await expect(page).toHaveURL(`${baseURL}/`);
  await page.goto(`${baseURL}/money?mode=withdraw`);
  await page.getByRole('radio', { name: 'Withdraw to Apple Cash', exact: true }).click();
  await page.getByLabel('Amount in USDC', { exact: true }).fill('25');
  await page.getByLabel('Amount in USDC', { exact: true }).blur();
  await expect(page.getByRole('button', { name: 'Digit 0', exact: true })).toBeInViewport({ ratio: 1 });
  await capture('withdraw-apple-cash', page.getByRole('heading', { name: 'Withdraw', exact: true }));
  await page.getByRole('button', { name: 'Review details', exact: true }).click();
  await capture('withdraw-review', page.getByRole('heading', { name: 'Withdraw', exact: true }));
  await page.getByRole('button', { name: 'Confirm demo withdrawal', exact: true }).click();
  await page.getByTestId('receipt-details').waitFor();
  await capture('withdraw-receipt', page.getByRole('heading', { name: 'Ready for what’s next.', exact: true }));
  await page.goto(`${baseURL}/send?phone=%2B13055550100`);
  await page.getByLabel('Amount in USDC', { exact: true }).fill('10');
  await page.getByTestId('review-transfer').click();
  await page.getByTestId('confirm-transfer').click();
  await page.getByRole('button', { name: 'Save contact name', exact: true }).click();
  await page.getByLabel('Contact name', { exact: true }).fill('Alex Rivera');
  await page.getByRole('button', { name: 'Save name', exact: true }).click();
  await expect(page.getByText('To Alex Rivera', { exact: true })).toBeVisible();
  await capture('named-receipt', page.getByRole('heading', { name: 'A little closer.', exact: true }));
  await page.goto(`${baseURL}/send`);
  await page.getByRole('button', { name: 'Pay Alex Rivera', exact: true }).waitFor();
  await capture('send-again', page.getByRole('heading', { name: 'Send to', exact: true }));
  await page.goto(`${baseURL}/contact?phone=%2B13055550100`);
  await page.getByRole('button', { name: 'Edit contact name', exact: true }).click();
  await page.getByLabel('Contact name', { exact: true }).fill('Alex Rivera');
  await capture('contact-name', page.getByRole('heading', { name: 'A familiar name', exact: true }));
  await page.getByRole('button', { name: 'Dismiss', exact: true }).click();
  await page.goto(`${baseURL}/send?phone=%2B13055550100`);
  await page.setViewportSize({ width: 390, height: 400 });
  const note = page.getByLabel('Payment note', { exact: true });
  await note.fill('Visible while I type');
  await expect(note).toBeInViewport({ ratio: 1 });
  await capture('typing-short-viewport');
  if (errors.length) throw new Error(errors.join('\n'));
  console.log(`Saved 7 UX previews to ${output}. No browser runtime errors.`);
} finally { await browser.close(); }
